export const MESSAGES = { ja: JA, en: EN };
export const LANGUAGES = ['ja', 'en'];
let current = 'ja';

export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'ja';
  return current;
}

export function getLanguage() {
  return current;
}

export function t(key, vars = {}, lang = current) {
  const dict = MESSAGES[lang] || JA;
  const s = key in dict ? dict[key] : JA[key];
  if (s === undefined) return key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
